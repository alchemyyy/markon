// Builds the GitHub renderer's files into src/gfm/vendor/.
// They are kept in the repository, so `npm run dev` and `npm run build` need neither Go nor the network.
//
//   gfm.wasm.gz                  gh-gfm-preview's renderer built for WebAssembly
//   wasm_exec.js.gz              Go's loader for it
//   mathjax.js.gz                MathJax 3 with TeX input and SVG output (npm mathjax, es5/tex-mml-svg.js)
//   mathjax-extensions.json.gz   every MathJax TeX extension, which its autoloader asks for by name
//   mermaid.js.gz, leaflet.js.gz, leaflet.css.gz, topojson.js.gz
//                                the page libraries gh-gfm-preview vendors for its own page
//   github-markdown.js           github-markdown-css split into its color-free rules and light/dark variables
//   chroma.js                    gh-gfm-preview's chroma code colors, and the same rules reading palette variables
//   THIRD_PARTY_LICENSES.txt
//
// gh-gfm-preview is built at a pinned commit (downloaded into node_modules/.cache/markon-gfm),
// with scripts/gfm/main.go and hook.go added to it.
// It needs Go 1.25 or later: GO=<path to go>, the `go` on PATH, or else a Go this script downloads into the cache.
//
// Run after changing scripts/gfm/ or a pinned version: npm run gen:gfm
