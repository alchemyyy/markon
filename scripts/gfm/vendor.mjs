/** JSON with every non-ASCII character escaped, so generated sources stay ASCII */
const asciiJson = value =>
	JSON.stringify(value, null, '\t').replace(
		/[\u007f-\uffff]/g,
		c => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`,
	)

async function download(url) {
	const response = await fetch(url)
	if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`)
	return Buffer.from(await response.arrayBuffer())
}

function run(command, args, options = {}) {
	const result = spawnSync(command, args, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, ...options })
	if (result.error) throw result.error
	if (result.status !== 0) {
		throw new Error(`${command} ${args.join(' ')} failed (${result.status}):\n${result.stdout}${result.stderr}`)
	}
	return result.stdout
}

/** Unpacks a .zip or .tar.gz archive with the system tar (bsdtar on Windows and macOS reads zip) */
function extract(archive, destination) {
	mkdirSync(destination, { recursive: true })
	run('tar', ['-xf', archive, '-C', destination])
}

function licenseText(directory) {
	const file = readdirSync(directory).find(name => /^(licen[cs]e|copying|unlicense)([.-]|$)/i.test(name))
	if (!file) throw new Error(`No license file in ${directory}`)
	return readFileSync(path.join(directory, file), 'utf8').trim()
}

/** An npm package unpacked into the cache; returns its directory */
async function npmPackage({ name, version }) {
	const directory = path.join(cache, `${name}-${version}`)
	const unpacked = path.join(directory, 'package')
	if (existsSync(path.join(unpacked, 'package.json'))) return unpacked
	const metadata = JSON.parse((await download(`https://registry.npmjs.org/${name}/${version}`)).toString('utf8'))
	const integrity = metadata.dist.integrity
	const split = integrity.indexOf('-')
	const bytes = await download(metadata.dist.tarball)
	const actual = createHash(integrity.slice(0, split)).update(bytes).digest('base64')
	if (actual !== integrity.slice(split + 1)) throw new Error(`${name}@${version}: integrity mismatch`)
	rmSync(directory, { recursive: true, force: true })
	mkdirSync(directory, { recursive: true })
	const archive = path.join(directory, 'package.tgz')
	writeFileSync(archive, bytes)
	extract(archive, directory)
	rmSync(archive)
	return unpacked
}

