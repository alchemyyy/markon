const output = path.join(root, 'src', 'gfm', 'vendor')
const cache = path.join(root, 'node_modules', '.cache', 'markon-gfm')
const GENERATED = '// Generated by scripts/gfm/vendor.mjs; do not edit.\n'
const RULE = `\n\n${'-'.repeat(72)}\n\n`

