function goVersionOf(go) {
	const result = spawnSync(go, ['env', 'GOVERSION'], { encoding: 'utf8' })
	const match = result.status === 0 ? /^go(\d+)\.(\d+)/.exec(result.stdout.trim()) : null
	return match ? [Number(match[1]), Number(match[2])] : null
}

/** A Go 1.25+ toolchain: GO, the `go` on PATH, or one downloaded into the cache */
async function ensureGo() {
	for (const candidate of [process.env.GO, 'go'].filter(Boolean)) {
		const version = goVersionOf(candidate)
		if (version && (version[0] > MINIMUM_GO[0] || (version[0] === MINIMUM_GO[0] && version[1] >= MINIMUM_GO[1]))) {
			return candidate
		}
	}
	const os = { win32: 'windows', darwin: 'darwin', linux: 'linux' }[process.platform]
	const arch = { x64: 'amd64', arm64: 'arm64' }[process.arch]
	if (!os || !arch)
		throw new Error(`No Go download for ${process.platform}/${process.arch}; set GO to a Go 1.25+ binary`)
	const directory = path.join(cache, `go${GO_VERSION}`)
	const binary = path.join(directory, 'go', 'bin', os === 'windows' ? 'go.exe' : 'go')
	if (existsSync(binary)) return binary
	const filename = `go${GO_VERSION}.${os}-${arch}.${os === 'windows' ? 'zip' : 'tar.gz'}`
	const releases = JSON.parse((await download('https://go.dev/dl/?mode=json&include=all')).toString('utf8'))
	const expected = releases.flatMap(release => release.files).find(file => file.filename === filename)?.sha256
	if (!expected) throw new Error(`go.dev lists no ${filename}`)
	console.log(`Downloading ${filename}`)
	const bytes = await download(`https://go.dev/dl/${filename}`)
	const actual = createHash('sha256').update(bytes).digest('hex')
	if (actual !== expected) throw new Error(`${filename}: sha256 ${actual}, expected ${expected}`)
	mkdirSync(cache, { recursive: true })
	const archive = path.join(cache, filename)
	writeFileSync(archive, bytes)
	rmSync(directory, { recursive: true, force: true })
	extract(archive, directory)
	rmSync(archive)
	return binary
}

/** A fresh checkout of gh-gfm-preview at the pinned commit with scripts/gfm/ added */
async function ghGfmPreviewCheckout() {
	const tarball = path.join(cache, `gh-gfm-preview-${GH_GFM_PREVIEW.commit}.tar.gz`)
	if (!existsSync(tarball)) {
		mkdirSync(cache, { recursive: true })
		const url = `https://codeload.github.com/${GH_GFM_PREVIEW.repository}/tar.gz/${GH_GFM_PREVIEW.commit}`
		writeFileSync(tarball, await download(url))
	}
	const checkout = path.join(cache, `gh-gfm-preview-${GH_GFM_PREVIEW.commit}`)
	rmSync(checkout, { recursive: true, force: true })
	extract(tarball, cache)
	if (!existsSync(path.join(checkout, 'go.mod'))) throw new Error(`${tarball} did not unpack to ${checkout}`)

	// ToHTML takes the parser options hook.go declares, for the source-line marks
	const appFile = path.join(checkout, 'internal', 'app', 'app.go')
	const app = readFileSync(appFile, 'utf8')
	const original = 'goldmark.WithParserOptions(parser.WithAutoHeadingID()),'
	const patched =
		'goldmark.WithParserOptions(append([]parser.Option{parser.WithAutoHeadingID()}, ExtraParserOptions...)...),'
	if (app.split(original).length !== 2)
		throw new Error('internal/app/app.go no longer builds its parser options as expected')
	writeFileSync(appFile, app.replace(original, patched))
	copyFileSync(path.join(here, 'hook.go'), path.join(checkout, 'internal', 'app', 'markon_hook.go'))
	mkdirSync(path.join(checkout, 'cmd', 'markon-wasm'), { recursive: true })
	copyFileSync(path.join(here, 'main.go'), path.join(checkout, 'cmd', 'markon-wasm', 'main.go'))
	return checkout
}

function goEnvironment() {
	const gopath = path.join(cache, 'gopath')
	return {
		...process.env,
		GOOS: 'js',
		GOARCH: 'wasm',
		CGO_ENABLED: '0',
		GOTOOLCHAIN: 'local',
		GOFLAGS: '-mod=mod',
		GOPATH: gopath,
		GOMODCACHE: path.join(gopath, 'pkg', 'mod'),
		GOCACHE: path.join(cache, 'gocache'),
		GOTELEMETRY: 'off',
	}
}

/** gh-gfm-preview's renderer as WebAssembly, Go's loader for it, and the licenses of what it contains */
function buildWasm(go, checkout) {
	const env = goEnvironment()
	const wasmFile = path.join(cache, 'gfm.wasm')
	run(go, ['build', '-trimpath', '-ldflags=-s -w', '-o', wasmFile, './cmd/markon-wasm'], { cwd: checkout, env })
	const goroot = run(go, ['env', 'GOROOT'], { env }).trim()
	const loader = [
		path.join(goroot, 'lib', 'wasm', 'wasm_exec.js'),
		path.join(goroot, 'misc', 'wasm', 'wasm_exec.js'),
	].find(existsSync)
	if (!loader) throw new Error(`No wasm_exec.js in ${goroot}`)

	// One JSON object per package, concatenated
	const listing = run(go, ['list', '-deps', '-json', './cmd/markon-wasm'], { cwd: checkout, env })
	const modules = new Map()
	for (const chunk of listing.split(/\n(?=\{)/)) {
		const module = JSON.parse(chunk).Module
		if (module && !module.Main && module.Dir) modules.set(module.Path, module)
	}
	const goVersion = run(go, ['env', 'GOVERSION'], { env }).trim().replace(/^go/, '')
	const notices = [
		`gh-gfm-preview@${GH_GFM_PREVIEW.commit} (github.com/${GH_GFM_PREVIEW.repository})\n\n${licenseText(checkout)}`,
		`Go ${goVersion} (runtime, standard library, wasm_exec.js)\n\n${licenseText(goroot)}`,
		...[...modules.values()]
			.sort((left, right) => left.Path.localeCompare(right.Path))
			.map(module => `${module.Path}@${module.Version}\n\n${licenseText(module.Dir)}`),
	]
	return { wasm: readFileSync(wasmFile), loader: readFileSync(loader), notices }
}

/** Renders a sample with the built renderer in Node, so a broken build never ships */
async function checkWasm(wasm, loader) {
	// wasm_exec.js defines globalThis.Go, with Node polyfills where it needs them
	vm.runInThisContext(loader.toString('utf8'))
	const go = new globalThis.Go()
	const { instance } = await WebAssembly.instantiate(wasm, go.importObject)
	void go.run(instance)
	const sample =
		'# Title\n\nText with :rocket:\n\n```js\nlet a = 1\n```\n\n```mermaid\ngraph TD\n```\n\n> [!NOTE]\n> Note\n'
	const result = globalThis.markonGfmRender(sample, 2)
	if (result.error) throw new Error(`gfm.wasm: ${result.error}`)
	const expectations = [
		[/<h1 [^>]*data-source-line="3"/, 'source line of the heading'],
		[/class="chroma"/, 'chroma highlighting'],
		[/<code class="language-mermaid">/, 'Mermaid code kept for the page'],
		[/markdown-alert-note/, 'GitHub alerts'],
		[/&#x1f680;|\u{1F680}/u, 'emoji shortcodes'],
	]
	for (const [pattern, what] of expectations) {
		if (!pattern.test(result.html)) throw new Error(`gfm.wasm lacks ${what}:\n${result.html}`)
	}
}

/** Every MathJax TeX extension, which its autoloader asks for as macros need them */
function mathjaxExtensions(directory) {
	const extensions = path.join(directory, 'es5', 'input', 'tex', 'extensions')
	const files = {}
	for (const name of readdirSync(extensions).sort()) {
		if (name.endsWith('.js')) files[name] = readFileSync(path.join(extensions, name), 'utf8')
	}
	return Buffer.from(JSON.stringify(files))
}

// ---------------------------------------------------------------------------------------------

const checkout = await ghGfmPreviewCheckout()
const githubMarkdownCss = await npmPackage(GITHUB_MARKDOWN_CSS)
const mathjax = await npmPackage(MATHJAX)
const go = await ensureGo()
const { wasm, loader, notices } = buildWasm(go, checkout)
await checkWasm(wasm, loader)

const generated = path.join(checkout, 'internal', 'server', 'static', 'generated')
const assets = {
	'gfm.wasm': wasm,
	'wasm_exec.js': loader,
	'mathjax.js': readFileSync(path.join(mathjax, 'es5', 'tex-mml-svg.js')),
	'mathjax-extensions.json': mathjaxExtensions(mathjax),
	...Object.fromEntries(
		PAGE_LIBRARIES.map(library => [library.asset, readFileSync(path.join(generated, library.file))]),
	),
}
const libraryNotices = []
for (const library of PAGE_LIBRARIES) {
	if (!library.license) continue
	const text = (await download(`https://raw.githubusercontent.com/${library.license}`)).toString('utf8').trim()
	libraryNotices.push(`${library.name}@${library.version}\n\n${text}`)
}
const licenses = [
	'Third-party code in src/gfm/vendor/ (generated by scripts/gfm/vendor.mjs)',
	...notices,
	`${GITHUB_MARKDOWN_CSS.name}@${GITHUB_MARKDOWN_CSS.version} (github-markdown.js)\n\n${licenseText(githubMarkdownCss)}`,
	`${MATHJAX.name}@${MATHJAX.version}\n\n${licenseText(mathjax)}`,
	...libraryNotices,
].join(RULE)

// Everything was built and checked; only now is the previous output replaced
mkdirSync(output, { recursive: true })
for (const [name, bytes] of Object.entries(assets)) {
	const compressed = gzipSync(bytes, { level: 9 })
	writeFileSync(path.join(output, `${name}.gz`), compressed)
	const sizes = `${(bytes.length / 1024).toFixed(0).padStart(6)} KB -> ${(compressed.length / 1024).toFixed(0).padStart(5)} KB`
	console.log(`${`${name}.gz`.padEnd(28)} ${sizes}`)
}
writeFileSync(path.join(output, 'github-markdown.js'), githubMarkdownModule(githubMarkdownCss))
writeFileSync(path.join(output, 'chroma.js'), chromaModule(checkout))
writeFileSync(path.join(output, 'THIRD_PARTY_LICENSES.txt'), `${licenses}\n`)
// The Go runtime started by checkWasm stays parked on its event queue
process.exit(0)
