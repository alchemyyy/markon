/** `{ "--name": "value" }` from the declarations of one CSS block body */
function variables(block) {
	const entries = [...block.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)].map(([, name, value]) => [name, value.trim()])
	return Object.fromEntries(entries)
}

/**
 * github-markdown.css opens with a block of size and font variables,
 * then one block of color variables per `prefers-color-scheme`;
 * every rule after them reads colors only from variables.
 */
function githubMarkdownModule(directory) {
	const css = readFileSync(path.join(directory, 'github-markdown.css'), 'utf8')
	const scheme = name => {
		const match = new RegExp(
			`@media \\(prefers-color-scheme: ${name}\\) \\{\\s*\\.markdown-body, \\[data-theme="${name}"\\] \\{([\\s\\S]*?)\\n  \\}\\n\\}\\n`,
		).exec(css)
		if (!match) throw new Error(`github-markdown.css has no ${name} color block`)
		return match
	}
	const dark = scheme('dark')
	const light = scheme('light')
	const base = /^\.markdown-body \{([\s\S]*?)\n\}\n/.exec(css)
	if (!base) throw new Error('github-markdown.css has no leading variable block')
	const rules = css.slice(Math.max(dark.index + dark[0].length, light.index + light[0].length)).trim()
	if (/#[0-9a-f]{3,8}\b/i.test(rules)) throw new Error('github-markdown.css rules hold literal colors')

	return [
		GENERATED,
		`// ${GITHUB_MARKDOWN_CSS.name}@${GITHUB_MARKDOWN_CSS.version} (MIT, Sindre Sorhus); see THIRD_PARTY_LICENSES.txt.\n\n`,
		'/** Size and font variables every GitHub color scheme shares */\n',
		`export const GITHUB_BASE_VARIABLES = ${asciiJson(variables(base[1]))}\n\n`,
		"/** GitHub's light color variables */\n",
		`export const GITHUB_LIGHT_VARIABLES = ${asciiJson(variables(light[1]))}\n\n`,
		"/** GitHub's dark color variables */\n",
		`export const GITHUB_DARK_VARIABLES = ${asciiJson(variables(dark[1]))}\n\n`,
		'/** Every `.markdown-body` rule; colors come only from the variables above */\n',
		`export const GITHUB_MARKDOWN_RULES = ${asciiJson(rules)}\n`,
	].join('')
}

/** chroma's GitHub light rules with each color replaced by the palette variable that means it */
function paletteChroma(light) {
	return light.replace(/#[0-9a-f]{6}\b/gi, color => {
		const variable = CHROMA_COLOR_VARIABLES[color.toLowerCase()]
		if (!variable) throw new Error(`chroma-github-light.css: no palette variable for ${color}`)
		return `var(${variable})`
	})
}

function chromaModule(checkout) {
	const generated = path.join(checkout, 'internal', 'server', 'static', 'generated')
	const light = readFileSync(path.join(generated, 'chroma-github-light.css'), 'utf8').trim()
	const dark = readFileSync(path.join(generated, 'chroma-github-dark.css'), 'utf8').trim()
	return [
		GENERATED,
		`// From gh-gfm-preview@${GH_GFM_PREVIEW.commit} (MIT); see THIRD_PARTY_LICENSES.txt.\n\n`,
		"/** gh-gfm-preview's code colors: chroma's GitHub style */\n",
		`export const CHROMA_GITHUB_LIGHT = ${asciiJson(light)}\n\n`,
		"/** gh-gfm-preview's code colors: chroma's GitHub dark style */\n",
		`export const CHROMA_GITHUB_DARK = ${asciiJson(dark)}\n\n`,
		"/** The GitHub style's rules with its colors read from palette variables */\n",
		`export const CHROMA_PALETTE = ${asciiJson(paletteChroma(light))}\n`,
	].join('')
}

